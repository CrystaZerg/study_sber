/**
 * MCP-сервер «Яндекс (ya.ru)» — read-only доступ к публичным данным Яндекса.
 *
 * Транспорт: stdio. Подключение из MCP-клиента выполняется запуском
 * собранного скрипта (см. README.md в этой папке).
 *
 * Все инструменты читают только публичные данные Яндекса и не выполняют
 * никаких побочных эффектов (ни на стороне Яндекс, ни на стороне клиента).
 */

import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { z } from 'zod';
import { homepageMeta, pingYandex, searchSuggest } from './yandex.ts';
import { yandexNews, yandexWeather } from './datasource.ts';

const server = new McpServer({
  name: 'yandex-read',
  version: '1.0.0',
});

/** Оборачивает результат инструмента в текстовый контент для MCP. */
function toTextContent(result: unknown) {
  return {
    content: [{ type: 'text' as const, text: JSON.stringify(result, null, 2) }],
  };
}

// ---------------------------------------------------------------------------
// Инструмент 1: проверка доступности ya.ru (без входных аргументов)
// ---------------------------------------------------------------------------
server.tool(
  'yandex_ping',
  'Проверка доступности Яндекса. Выполняет HTTPS-запрос к главной странице ya.ru и возвращает HTTP-статус, заголовки (server, content-type), задержки по этапам соединения (DNS, connect, TLS, ожидание ответа, общий итог) и IP-адрес удалённого сервера. Используйте, когда пользователь просит «проверить, работает ли Яндекс», «доступен ли ya.ru», «почему не открывается Яндекс», «какая задержка у Яндекса» или спрашивает о статусе/доступности сервиса.',
  async () => toTextContent(await pingYandex()),
);

// ---------------------------------------------------------------------------
// Инструмент 2: метаданные главной страницы ya.ru (без входных аргументов)
// ---------------------------------------------------------------------------
server.tool(
  'yandex_homepage_meta',
  'Метаданные главной страницы Яндекса. Читает главную страницу ya.ru и возвращает HTTP-статус, наличие редиректа и финальный URL, HTML-заголовок страницы (<title>), мета-описание и размер HTML. Используйте, когда пользователь спрашивает «какой title у ya.ru», «что написано на главной странице Яндекса», «куда редиректит ya.ru», «какой размер главной страницы Яндекса» или хочет узнать служебную информацию о главной странице. Это чтение, изменений не вносит.',
  async () => toTextContent(await homepageMeta()),
);

// ---------------------------------------------------------------------------
// Инструмент 3: поисковые подсказки Яндекса (аргументы: query, limit)
// ---------------------------------------------------------------------------
server.tool(
  'yandex_search_suggest',
  'Поисковые подсказки Яндекса. Возвращает поисковые подсказки (автодополнение) для заданной фразы через публичный эндпоинт suggest.yandex.ru без авторизации; подсказки отражают популярные запросы пользователей. Используйте, когда пользователь спрашивает «какие есть подсказки у Яндекса для ...», «что поисковая система предлагает по запросу ...», «автодополнение для запроса ...» или хочет узнать, как формулируют запросы другие пользователи. Это чтение, побочных эффектов нет.',
  {
    query: z
      .string()
      .min(1, 'Поле query не должно быть пустым')
      .describe('Фраза, для которой нужны подсказки. Примеры: "погода", "сбербанк".'),
    limit: z
      .number()
      .int()
      .min(1)
      .max(20)
      .default(5)
      .describe('Максимальное число подсказок в ответе (от 1 до 20).'),
  },
  async (args: { query: string; limit?: number }) =>
    toTextContent(await searchSuggest(args.query, args.limit ?? 5)),
);

// ---------------------------------------------------------------------------
// Инструмент 4: погода (аргумент: city)
// ---------------------------------------------------------------------------
server.tool(
  'yandex_weather',
  'Погода в заданном городе. Возвращает текущую температуру, ощущаемую температуру, влажность, скорость и направление ветра, описание погоды, время наблюдения и краткий прогноз на сегодня (мин/макс температура и описание). Данные берутся из открытого сервиса wttr.in (без API-ключа). Используйте, когда пользователь спрашивает «какая погода в Москве», «температура в Санкт-Петербурге», «прогноз погоды», «холодно ли на улице», «какая сейчас погода в <городе>». Это чтение, изменений не вносит.',
  {
    city: z
      .string()
      .min(1)
      .describe('Город (англ или рус.): "moscow", "москва", "saint petersburg".'),
  },
  async (args: { city: string }) => toTextContent(await yandexWeather(args.city)),
);

// ---------------------------------------------------------------------------
// Инструмент 5: актуальные новости RU (аргументы: limit, region)
// ---------------------------------------------------------------------------
server.tool(
  'yandex_news',
  'Актуальные новости России и мира. Возвращает список последних новостей (заголовок, источник, ссылка, дата публикации). Источник — открытый RSS Google News Russia (в этой среде Яндекс-новости заблокированы, поэтому используется рабочий фид Google News RU). Используйте, когда пользователь спрашивает «актуальные новости», «последние новости России», «что происходит в мире», «дай сводку новостей». Это чтение, побочных эффектов нет.',
  {
    limit: z
      .number()
      .int()
      .min(1)
      .max(20)
      .default(8)
      .describe('Максимальное число новостей в ответе (от 1 до 20).'),
    region: z
      .string()
      .default('RU')
      .describe('Регион новостей. Принимает "RU"; прочие значения игнорируются (используется базовый RU-фид).'),
  },
  async (args: { limit?: number; region?: string }) =>
    toTextContent(await yandexNews(args.limit ?? 8, args.region ?? 'RU')),
);

// ---------------------------------------------------------------------------
// Запуск (stdio-транспорт)
// ---------------------------------------------------------------------------
const transport = new StdioServerTransport();
await server.connect(transport);
